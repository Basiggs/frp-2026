import glob, json, os

PRJ = os.path.dirname(os.path.abspath(__file__))


def load(p):
    return json.load(open(os.path.join(PRJ, p), encoding="utf-8"))


def main():
    data = load("data.json")["videos"]
    subjects = sorted({v["course"] for v in data if v.get("course")})
    minutes = round(sum(v.get("seconds") or 0 for v in data) / 60)
    questions = sum(len(v.get("quiz") or []) for v in data)
    chapters = sum(1 for v in data if v.get("chapters"))
    checks = [json.load(open(p)) for p in glob.glob(os.path.join(PRJ, "runs", "*", "check.json"))]
    checked = len(checks)
    passed = sum(1 for c in checks if c.get("ok"))
    stopped = checked - passed
    grades = len(load("grades.json"))

    lines = [
        "# School topics as videos — results",
        "",
        f"{len(data)} lessons, made by one pipeline: chat model writes the script, an AI check reads it, "
        "pictures and voice are generated, ffmpeg cuts the video.",
        "",
        "## Four numbers",
        "",
        f"- **{len(data)}** videos — `data.json`",
        f"- **{len(subjects)}** subjects: {', '.join(subjects)} — `data.json`",
        f"- **{minutes} min** of video — `data.json`",
        f"- **{questions}** quiz questions — `data.json`",
        "",
        "## All numbers with their file",
        "",
        "| number | what | file |",
        "|---|---|---|",
        f"| {len(data)} | videos in the gallery | `data.json` |",
        f"| {len(subjects)} | subjects | `data.json` |",
        f"| {minutes} | minutes of finished video | `data.json` |",
        f"| {questions} | quiz questions | `data.json` |",
        f"| {chapters} | videos with chapter marks | `data.json` |",
        f"| {grades} | videos with a school grade | `grades.json` |",
        f"| {checked} | scripts sent to the AI check | `runs/*/check.json` |",
        f"| {passed} | scripts that passed the AI check | `runs/*/check.json` |",
        f"| {stopped} | scripts the AI check stopped | `runs/*/check.json` |",
        "",
        "## What is still weak",
        "",
        f"- Only {checked} of {len(data)} scripts were sent to the AI check ({passed} passed, {stopped} stopped); "
        "the rest were made before the check existed.",
        "- The pictures come from the image model at 1536 px and are upscaled to 1080p, so they look soft.",
        "- A full video takes about 3 minutes to build, so a live demo needs a backup.",
        "",
        f"_Generated by `make_results.py` from the files above._",
    ]
    open(os.path.join(PRJ, "results.md"), "w", encoding="utf-8").write("\n".join(lines) + "\n")
    print(f"results.md: {len(data)} videos, {len(subjects)} subjects, {minutes} min, {questions} questions, "
          f"{checked} checked / {passed} passed")


main()
