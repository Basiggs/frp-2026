import json, urllib.request

TEXTS = [
    "Арифметическая прогрессия — это последовательность чисел, в которой каждое следующее число отличается от предыдущего на одно и то же число. Это число называют разностью и обозначают буквой дэ.",
    "Например, два, пять, восемь, одиннадцать. Каждый раз мы прибавляем три. Значит, разность этой прогрессии равна трём, и она возрастающая.",
    "Прогрессия может и убывать. Возьмём двадцать, семнадцать, четырнадцать, одиннадцать. Здесь мы каждый раз вычитаем три, поэтому разность равна минус трём.",
    "Формула энного члена: а эн равно а один плюс эн минус один, умноженное на дэ. Проверим: а пятое равно два плюс четыре умножить на три, то есть четырнадцать.",
    "А теперь попробуйте сами. Первый член равен двум, разность равна трём. Найдите двадцатый член прогрессии и запишите ответ.",
]

for i, text in enumerate(TEXTS, 1):
    req = urllib.request.Request(
        "http://127.0.0.1:19040/v1/audio/speech",
        data=json.dumps({"input": text, "language": "ru"}).encode(),
        headers={"Content-Type": "application/json"})
    with urllib.request.urlopen(req) as r, open(f"assets/audio/v{i}.wav", "wb") as f:
        f.write(r.read())
    print("vo", i, "ok")
